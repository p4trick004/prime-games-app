-- Prime Games — Phase 3 (customer-centred): 0009 KYC private Storage
-- Target: poaxanthiifatydqbnqq.supabase.co (storage schema). Idempotent + reversible.
-- Depends on: 0001_helpers.sql (current_customer_id), 0002_customers.sql.
--
-- Private bucket for OPTIONAL KYC document uploads. Objects live under
-- kyc-private/<customer_id>/<uuid>. Access:
--   * authenticated customers: SELECT + INSERT only within their OWN folder.
--   * service_role (backend/admin): full access (bypasses RLS); admin actions are
--     authorized in the backend via the ADMIN_PASSWORD HMAC, never in the browser.
--   * anon: no policies -> denied.
--   * No customer UPDATE/DELETE policies -> verification/removal is admin-only.
-- Downloads are served via short-lived signed URLs generated by the backend.
-- The service_role key is NEVER exposed to the frontend.

-- 1) Private bucket (5 MB cap; JPEG/PNG/PDF only) ---------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('kyc-private', 'kyc-private', false, 5242880, array['image/jpeg', 'image/png', 'application/pdf'])
on conflict (id) do update
  set public = false,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

-- 2) Object policies (storage.objects has RLS enabled by Supabase) ----------
drop policy if exists kyc_private_select_own on storage.objects;
create policy kyc_private_select_own on storage.objects
  for select to authenticated
  using (
    bucket_id = 'kyc-private'
    and (storage.foldername(name))[1] = public.current_customer_id()::text
  );

drop policy if exists kyc_private_insert_own on storage.objects;
create policy kyc_private_insert_own on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'kyc-private'
    and (storage.foldername(name))[1] = public.current_customer_id()::text
  );